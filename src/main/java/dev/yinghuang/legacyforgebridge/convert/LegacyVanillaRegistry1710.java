    private LegacyVanillaRegistry1710() { }

    public static Optional<Entry> resolve(String owner,String fieldName) {
        if (owner == null || fieldName == null) return Optional.empty();
        if (ITEMS_OWNER.equals(owner)) return Optional.ofNullable(ITEMS.get(fieldName));
        if (BLOCKS_OWNER.equals(owner)) return Optional.ofNullable(BLOCKS.get(fieldName));
        return Optional.empty();
    }

    public static Optional<Entry> resolve(LegacyRecipeAnalyzer.FieldValue field) {
        return field == null ? Optional.empty() : resolve(field.owner(),field.name());
    }

    static int knownItemFields() { return ITEMS.size(); }
    static int knownBlockFields() { return BLOCKS.size(); }
